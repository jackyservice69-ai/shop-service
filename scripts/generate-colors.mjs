import { readFileSync, writeFileSync } from "node:fs";
const colors = JSON.parse(
  readFileSync(
    new URL("../shared/customer-colors.json", import.meta.url),
    "utf8",
  ),
);
const declarations = Object.entries(colors).flatMap(([role, shades]) =>
  typeof shades === "string"
    ? [`  --palette-${role}: ${shades};`]
    : Object.entries(shades).map(
        ([shade, value]) =>
          `  --palette-${role}${shade === "DEFAULT" ? "" : "-" + shade}: ${value};`,
      ),
);
writeFileSync(
  new URL("../src/brand.generated.css", import.meta.url),
  `/* Generated by scripts/generate-colors.mjs from shared/customer-colors.json. */\n:root {\n${declarations.join("\n")}\n}\n`,
);
